import { jsPDF } from 'jspdf';
import { autoTable } from 'jspdf-autotable';
import { expenseClaimReportFilename, expenseReportFilename } from '../domain/expenseReport.js';

const ink = [25, 39, 36];
const muted = [91, 105, 100];
const line = [213, 221, 216];
const tint = [241, 245, 242];
const accent = [24, 91, 74];
const warning = [157, 92, 19];
const pageWidth = 210;
const pageHeight = 297;
const margin = 14;
const formatSen = (sen, currency) => `${currency} ${(Number(sen || 0) / 100).toLocaleString('en-MY', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const signedSen = (sen, currency) => `${Number(sen)>0?'+':''}${formatSen(sen,currency)}`;
const dateTime = value => new Intl.DateTimeFormat('en-MY', {
  timeZone: 'Asia/Kuala_Lumpur', year: 'numeric', month: 'short', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false,
}).format(new Date(value));
const rangeLabel = filters => filters.from || filters.to ? `${filters.from || 'Beginning'} to ${filters.to || 'Current'}` : 'All available dates';
const pdfText = value => String(value ?? '').replace(/[–—−]/g, '-');
const reportFont = pdf => pdf.__myfinExpenseFont || 'helvetica';

function configureReportFont(pdf, { fontBase64 = '', fontFamily = '', fontFilename = '' } = {}) {
  if (!fontBase64 || !fontFamily || !fontFilename) return;
  pdf.addFileToVFS(fontFilename, fontBase64);
  pdf.addFont(fontFilename, fontFamily, 'normal');
  pdf.addFont(fontFilename, fontFamily, 'bold');
  pdf.__myfinExpenseFont = fontFamily;
}

function fitMetricValue(pdf, value, width, preferredSize = 9, maximumLines = 2) {
  let size = preferredSize, lines = [];
  for (; size >= 6; size -= .5) {
    pdf.setFontSize(size);
    lines = pdf.splitTextToSize(pdfText(value), width);
    if (lines.length <= maximumLines) break;
  }
  if (lines.length > maximumLines) {
    lines = lines.slice(0, maximumLines);
    let tail = lines.at(-1);
    while (tail && pdf.getTextWidth(`${tail}...`) > width) tail = tail.slice(0, -1);
    lines[lines.length - 1] = `${tail}...`;
  }
  return lines;
}

function reportHeader(pdf, report, continuation = false) {
  pdf.setTextColor(...ink); pdf.setFont(reportFont(pdf), 'bold'); pdf.setFontSize(continuation ? 9 : 18);
  pdf.text(continuation ? report.company.name : report.title, margin, continuation ? 12 : 17);
  pdf.setFont(reportFont(pdf), 'normal'); pdf.setTextColor(...muted); pdf.setFontSize(8);
  if (continuation) pdf.text(report.title || 'Expense report', pageWidth - margin, 12, { align: 'right' });
  else {
    pdf.text(`${report.workspace.name} / ${report.company.name}`, margin, 23);
    if (report.company.registration) pdf.text(`Registration: ${report.company.registration}`, margin, 28);
    pdf.text(report.kind === 'expense_claim' ? `Claim: ${report.claim.reference}` : `Report period: ${rangeLabel(report.filters || {})}`, pageWidth - margin, 17, { align: 'right' });
    pdf.text(`Generated: ${dateTime(report.generatedAt)} MYT`, pageWidth - margin, 23, { align: 'right' });
    pdf.text(`Generated by: ${report.actor.name}`, pageWidth - margin, 28, { align: 'right' });
    pdf.text(`Scope: ${report.scope?.label || 'Records visible to this user'}`, pageWidth - margin, 33, { align: 'right' });
  }
  pdf.setDrawColor(...accent); pdf.setLineWidth(continuation ? .25 : .7); pdf.line(margin, continuation ? 16 : 36, pageWidth - margin, continuation ? 16 : 36);
}

function sectionTitle(pdf, title, y) {
  pdf.setFont(reportFont(pdf), 'bold'); pdf.setFontSize(10); pdf.setTextColor(...ink); pdf.text(title, margin, y);
  return y + 4;
}

function addTable(pdf, report, { startY, head, body, columnStyles = {}, compact = false }) {
  autoTable(pdf, {
    startY,
    margin: { left: margin, right: margin, top: 22, bottom: 19 },
    head: [head.map(pdfText)], body:body.map(row=>row.map(pdfText)),
    theme: 'plain', showHead: 'everyPage', rowPageBreak: 'avoid',
    styles: { font: reportFont(pdf), fontSize: compact ? 7 : 7.5, cellPadding: compact ? 1.25 : 1.8, textColor: ink, overflow: 'linebreak', lineColor: line, lineWidth: { bottom: .12 } },
    headStyles: { fontStyle: 'bold', fillColor: tint, textColor: accent, lineColor: line, lineWidth: { bottom: .25 } },
    alternateRowStyles: { fillColor: [249, 250, 249] },
    columnStyles,
    didDrawPage(data) { if (data.pageNumber > 1 || pdf.getCurrentPageInfo().pageNumber > 1) reportHeader(pdf, report, true); },
  });
  return pdf.lastAutoTable.finalY;
}

function ensurePage(pdf, report, y, required = 35) {
  if (y + required <= pageHeight - 20) return y;
  pdf.addPage(); reportHeader(pdf, report, true); return 23;
}

function addPageFooters(pdf, report) {
  const pages=pdf.getNumberOfPages();
  for(let page=1;page<=pages;page++){
    pdf.setPage(page);pdf.setDrawColor(...line);pdf.line(margin,pageHeight-14,pageWidth-margin,pageHeight-14);
    pdf.setFont(reportFont(pdf),'normal');pdf.setFontSize(6.5);pdf.setTextColor(...muted);
    pdf.text(`Generated ${dateTime(report.generatedAt)} MYT`,margin,pageHeight-9);
    pdf.text(`Page ${page} of ${pages}`,pageWidth-margin,pageHeight-9,{align:'right'});
  }
}

export function createExpenseReportPdf(report, fontOptions = {}) {
  if (!report?.company?.name || !report?.generatedAt || !Array.isArray(report.lines)) throw new Error('The expense report is incomplete.');
  const pdf = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait', compress: true });
  configureReportFont(pdf, fontOptions);
  reportHeader(pdf, report);
  let y = 43;
  const metrics = [
    ['Expenses', String(report.totals.count)],
    ['Recorded total', formatSen(report.totals.totalSen, report.currency)],
    ['Paid', formatSen(report.totals.paidSen, report.currency)],
    ['Outstanding', formatSen(report.totals.outstandingSen, report.currency)],
    ['Evidence', `${report.totals.evidenceCount}/${report.totals.count}`],
  ];
  const metricWidth = (pageWidth - margin * 2 - 4 * 3) / 5;
  metrics.forEach(([label, value], index) => {
    const x = margin + index * (metricWidth + 3);
    pdf.setFillColor(...tint); pdf.roundedRect(x, y, metricWidth, 18, 1.5, 1.5, 'F');
    pdf.setFont(reportFont(pdf), 'normal'); pdf.setFontSize(6.5); pdf.setTextColor(...muted); pdf.text(label.toUpperCase(), x + 2.2, y + 5);
    pdf.setFont(reportFont(pdf), 'bold'); pdf.setFontSize(index === 0 ? 12 : 9); pdf.setTextColor(...ink);
    const fitted=fitMetricValue(pdf,value,metricWidth-4,index===0?12:9);
    pdf.text(fitted,x+2.2,y+(fitted.length>1?10.7:12.5),{lineHeightFactor:1.05});
  });
  y += 25;

  if(Number(report.totals.draftCount||0)>0){
    pdf.setFillColor(...tint);pdf.roundedRect(margin,y-2,pageWidth-margin*2,11,1.5,1.5,'F');
    pdf.setFont(reportFont(pdf),'bold');pdf.setFontSize(7);pdf.setTextColor(...accent);
    pdf.text('DRAFTS / NOT POSTED',margin+3,y+2.5);
    pdf.setFont(reportFont(pdf),'normal');pdf.setTextColor(...ink);
    const draftText=`${report.totals.draftCount} draft${Number(report.totals.draftCount)===1?'':'s'} · ${formatSen(report.totals.draftSen,report.currency)} excluded from recorded, paid, outstanding, ageing, and cash totals.`;
    pdf.text(fitMetricValue(pdf,draftText,pageWidth-margin*2-61,7,1),margin+58,y+2.5);
    y+=15;
  }

  y = sectionTitle(pdf, 'Status summary', y);
  y = addTable(pdf, report, {
    startY: y,
    head: ['Status', 'Records', 'Amount'],
    body:report.detailsAvailable===false
      ? [['Line-level status breakdown omitted - use a narrower range',String(report.totals.count),'-']]
      : report.byStatus.length ? report.byStatus.map(row => [row.label, String(row.count), formatSen(row.amountSen, report.currency)])
        : [['No matching expenses', '0', formatSen(0, report.currency)]],
    compact: true,
    columnStyles: { 0: { cellWidth: 110 }, 1: { cellWidth: 28, halign: 'right' }, 2: { cellWidth: 44, halign: 'right' } },
  }) + 7;

  y = ensurePage(pdf, report, y, 45);
  y = sectionTitle(pdf, 'Category and payment source', y);
  const maxSummary = Math.max(report.byCategory.length, report.byPaymentSource.length, 1);
  y = addTable(pdf, report, {
    startY: y,
    head: ['Category', 'Amount', 'Payment source', 'Amount'],
    body: Array.from({ length: maxSummary }, (_, index) => {
      const category = report.byCategory[index], source = report.byPaymentSource[index];
      return [category ? `${category.label}${category.draftCount?`\n${category.draftCount} drafts · ${formatSen(category.draftSen,report.currency)} not posted`:''}` : '',
        category ? formatSen(category.amountSen, report.currency) : '', source?.label || '', source ? formatSen(source.amountSen, report.currency) : ''];
    }),
    compact: true,
    columnStyles: { 0: { cellWidth: 50 }, 1: { cellWidth: 39, halign: 'right' }, 2: { cellWidth: 54 }, 3: { cellWidth: 39, halign: 'right' } },
  }) + 8;

  if (report.periods?.length) {
    y = ensurePage(pdf, report, y, 48);
    y = sectionTitle(pdf, `Cash expense by ${report.filters?.grain || 'period'}`, y);
    y = addTable(pdf, report, {
      startY:y,
      head:['Period','Claims','Recorded','Paid','Outstanding','Cash paid'],
      body:report.periods.map(row=>[row.label,row.draftCount?`${row.count} posted\n${row.draftCount} drafts`:String(row.count),
        row.draftCount?`${formatSen(row.totalSen,report.currency)}\n${formatSen(row.draftSen,report.currency)} drafts not posted`:formatSen(row.totalSen,report.currency),
        formatSen(row.paidSen,report.currency),formatSen(row.outstandingSen,report.currency),formatSen(row.cashOutSen,report.currency)]),
      compact:true,
      columnStyles:{0:{cellWidth:34},1:{cellWidth:20,halign:'right'},2:{cellWidth:32,halign:'right'},3:{cellWidth:32,halign:'right'},
        4:{cellWidth:32,halign:'right'},5:{cellWidth:32,halign:'right'}},
    })+7;
  }

  if (report.ageing?.length || report.byClaimant?.length) {
    y=ensurePage(pdf,report,y,45);
    y=sectionTitle(pdf,'Claim ageing and people',y);
    const rowCount=Math.max(report.ageing?.length||0,report.byClaimant?.length||0,1);
    y=addTable(pdf,report,{
      startY:y,head:['Ageing','Claims','Outstanding','Submitted by','Claims','Recorded'],
      body:Array.from({length:rowCount},(_,index)=>{
        const age=report.ageing?.[index],claimant=report.byClaimant?.[index];
        return [age?.label||'',age?String(age.count):'',age?formatSen(age.outstandingSen??age.amountSen,report.currency):'',
          claimant?.name||claimant?.label||'',claimant?(claimant.draftCount?`${claimant.count} posted\n${claimant.draftCount} drafts`:String(claimant.count)):'',
          claimant?(claimant.draftCount?`${formatSen(claimant.totalSen??claimant.amountSen,report.currency)}\n${formatSen(claimant.draftSen,report.currency)} drafts not posted`:formatSen(claimant.totalSen??claimant.amountSen,report.currency)):''];
      }),compact:true,
      columnStyles:{0:{cellWidth:31},1:{cellWidth:17,halign:'right'},2:{cellWidth:32,halign:'right'},
        3:{cellWidth:46},4:{cellWidth:18,halign:'right'},5:{cellWidth:38,halign:'right'}},
    })+7;
  }

  if(report.oldestOutstanding?.length){
    y=ensurePage(pdf,report,y,45);y=sectionTitle(pdf,'Oldest outstanding claims',y);
    y=addTable(pdf,report,{startY:y,head:['Expense','Submitted by','Category','Due','Age','Outstanding'],
      body:report.oldestOutstanding.map(row=>[`${row.date||'-'}\n${row.reference}`,row.claimantName,row.category,row.dueDate||'-',`${row.ageDays} days`,formatSen(row.outstandingSen,report.currency)]),
      compact:true,columnStyles:{0:{cellWidth:35},1:{cellWidth:43},2:{cellWidth:29},3:{cellWidth:25},4:{cellWidth:22,halign:'right'},5:{cellWidth:28,halign:'right'}}})+7;
  }

  const pettyInsights=report.pettyCash?.insights;
  if(pettyInsights){
    y=ensurePage(pdf,report,y,45);y=sectionTitle(pdf,'Petty cash usage',y);
    if(pettyInsights.restricted){
      y=addTable(pdf,report,{startY:y,head:['Visible scope','Claim payments'],
        body:[[report.scope?.label||'My claims',formatSen(pettyInsights.claimDisbursementSen,report.currency)]],compact:true,
        columnStyles:{0:{cellWidth:120},1:{cellWidth:62,halign:'right'}}})+7;
    }else{
      y=addTable(pdf,report,{startY:y,head:['Fund','Balance at period end','Replenished','Spent','Adjustments','Reversals'],
        body:pettyInsights.funds.length?pettyInsights.funds.map(fund=>[fund.name,formatSen(fund.balanceSen,report.currency),
          formatSen(fund.replenishmentSen,report.currency),formatSen(fund.disbursementSen,report.currency),
          signedSen(fund.adjustmentSen,report.currency),signedSen(fund.reversalSen,report.currency)]):[['All funds','-', '-',formatSen(pettyInsights.claimDisbursementSen,report.currency),'-','-']],
        compact:true,columnStyles:{0:{cellWidth:42},1:{cellWidth:28,halign:'right'},2:{cellWidth:28,halign:'right'},3:{cellWidth:28,halign:'right'},4:{cellWidth:28,halign:'right'},5:{cellWidth:28,halign:'right'}}})+7;
    }
  }

  if(report.detailsAvailable!==false){
    y = ensurePage(pdf, report, y, 50);
    y = sectionTitle(pdf, 'Expense details', y);
    y = addTable(pdf, report, {
      startY: y,
      head: ['Date / ref.', 'Expense / payee', 'Category', 'Status / source', 'Evidence', 'Amount'],
      body: report.lines.length ? report.lines.map(row => [
        `${row.date || '-'}\n${row.reference}`,
        `${row.description}${row.payee !== '-' ? `\n${row.payee}` : ''}${row.links.length ? `\nLinks: ${row.links.join(', ')}` : ''}`,
        row.category,
        `${row.statusLabel}${row.dueDate ? `\nDue ${row.dueDate}` : row.paidOn ? `\nPaid ${row.paidOn}` : ''}\n${row.paymentSource}`,
        row.evidence,
        formatSen(row.totalSen, report.currency),
      ]) : [['-', 'No matching expenses', '-', '-', '-', formatSen(0, report.currency)]],
      columnStyles: { 0: { cellWidth: 25 }, 1: { cellWidth: 52 }, 2: { cellWidth: 25 }, 3: { cellWidth: 36 }, 4: { cellWidth: 18 }, 5: { cellWidth: 26, halign: 'right' } },
    }) + 8;
  }else{
    y=ensurePage(pdf,report,y,28);
    pdf.setFillColor(...tint);pdf.roundedRect(margin,y,pageWidth-margin*2,21,1.5,1.5,'F');
    pdf.setFont(reportFont(pdf),'bold');pdf.setFontSize(7.5);pdf.setTextColor(...accent);pdf.text('DETAIL ROWS OMITTED',margin+3,y+5);
    pdf.setFont(reportFont(pdf),'normal');pdf.setTextColor(...ink);pdf.setFontSize(7);
    const omission=report.detailOmission||{},omissionText=omission.reason==='report_limit'
      ? `This role-scoped report contains ${omission.totalCount||report.totals.count} records. Detailed rows were omitted because the PDF detail limit is ${omission.limit||omission.returnedCount||'bounded'} records. The summary totals and distributions remain authoritative; use narrower dates for line-level detail.`
      : 'Detailed claim rows were omitted because a matching role-scoped server projection was unavailable. The summary totals and distributions remain authoritative.';
    pdf.text(pdf.splitTextToSize(omissionText,pageWidth-margin*2-6),margin+3,y+10);
    y+=29;
  }

  const petty = report.pettyCash || {};
  if (petty.funds?.length || petty.movements?.length) {
    y = ensurePage(pdf, report, y, 62);
    const pettyScope = petty.funds.length === 1 ? ` - ${petty.funds[0].name}` : '';
    y = sectionTitle(pdf, `Petty cash reconciliation${pettyScope}`, y);
    if (petty.complete === false) {
      pdf.setFont(reportFont(pdf), 'normal'); pdf.setFontSize(7); pdf.setTextColor(...warning);
      pdf.text('Movement detail is limited to the loaded ledger page. Load earlier movements before producing a complete reconciliation.', margin, y + 1);
      y += 5;
    }
    const s = petty.summary;
    y = addTable(pdf, report, {
      startY: y,
      head: ['Opening', 'Replenished', 'Spent', 'Adjustments / reversals', 'Expected cash', 'Counted / variance'],
      body: [[
        formatSen(s.openingBalanceSen, report.currency),
        formatSen(s.replenishmentsSen, report.currency),
        formatSen(s.disbursementsSen, report.currency),
        `Adjust +${formatSen(s.adjustmentInSen, report.currency)} / -${formatSen(s.adjustmentOutSen, report.currency)}\nReverse +${formatSen(s.reversalInSen, report.currency)} / -${formatSen(s.reversalOutSen, report.currency)}\nPrior counts +${formatSen(s.priorCountInSen, report.currency)} / -${formatSen(s.priorCountOutSen, report.currency)}`,
        formatSen(s.expectedBalanceSen, report.currency),
        s.countedBalanceSen == null ? 'Not counted' : `${formatSen(s.countedBalanceSen, report.currency)}\nVariance ${formatSen(s.varianceSen, report.currency)}`,
      ]],
      compact: true,
      columnStyles: Object.fromEntries(Array.from({ length: 6 }, (_, index) => [index, { cellWidth: 182 / 6, halign: index ? 'right' : 'left' }])),
    }) + 5;
    const fundNames = new Map(petty.funds.map(fund => [fund.id, fund.name]));
    y = addTable(pdf, report, {
      startY: y,
      head: ['Effective date', 'Fund', 'Movement', 'Reference / reason', 'Amount', 'Balance after'],
      body: petty.movements.length ? petty.movements.map(row => [
        row.date || '-', fundNames.get(row.fundId) || 'Petty cash', row.type,
        `${row.reference}${row.reason !== '-' ? `\n${row.reason}` : ''}`,
        signedSen(row.signedAmountSen, report.currency), row.balanceAfterSen == null ? '-' : formatSen(row.balanceAfterSen, report.currency),
      ]) : [['-', petty.funds.map(fund => fund.name).join(', '), 'No movements in period', '-', '-', formatSen(petty.summary.fundBalanceSen, report.currency)]],
      compact: true,
      columnStyles: { 0: { cellWidth: 23 }, 1: { cellWidth: 31 }, 2: { cellWidth: 28 }, 3: { cellWidth: 50 }, 4: { cellWidth: 25, halign: 'right' }, 5: { cellWidth: 25, halign: 'right' } },
    }) + 7;
  }

  y = ensurePage(pdf, report, y, 30);
  pdf.setFillColor(...tint); pdf.roundedRect(margin, y, pageWidth - margin * 2, 19, 1.5, 1.5, 'F');
  pdf.setFont(reportFont(pdf), 'bold'); pdf.setFontSize(7.5); pdf.setTextColor(...accent); pdf.text('CONTROL NOTE', margin + 3, y + 5);
  pdf.setFont(reportFont(pdf), 'normal'); pdf.setTextColor(...ink); pdf.setFontSize(7);
  const note = report.detailsAvailable===false
    ? 'This report uses the role-scoped server summary. Generate a narrower report or individual claim reports before relying on line-level detail.'
    : 'This report summarizes the records visible under the selected filters. Attached evidence, lifecycle history, petty cash ledger entries, and source records remain the audit authority. Retain the report with its supporting documents.';
  pdf.text(pdf.splitTextToSize(note, pageWidth - margin * 2 - 6), margin + 3, y + 10);

  addPageFooters(pdf,report);
  return pdf;
}

export async function downloadExpenseReportPdf(report, { shouldSave = () => true } = {}) {
  const { expensePdfFontOptions } = await import('./expensePdfFont.js');
  if (!shouldSave()) return null;
  const pdf = createExpenseReportPdf(report, expensePdfFontOptions());
  if (!shouldSave()) return null;
  pdf.save(expenseReportFilename(report));
  return pdf;
}

const snapshotText = (snapshot, currency) => {
  if(!snapshot || !Object.values(snapshot).some(value=>value!==''&&value!==false&&value!==0))return '-';
  const status=(snapshot.effectiveStatus||snapshot.status||'recorded').replaceAll('_',' ');
  const amounts=snapshot.amountSen||snapshot.paidAmountSen||snapshot.outstandingAmountSen
    ? ` · total ${formatSen(snapshot.amountSen,currency)} · paid ${formatSen(snapshot.paidAmountSen,currency)} · due ${formatSen(snapshot.outstandingAmountSen,currency)}`:'';
  const timing=snapshot.dueDate?` · due ${snapshot.dueDate}`:snapshot.paidOn?` · paid ${snapshot.paidOn}`:'';
  return `${status}${amounts}${timing}${snapshot.voided?' · voided':''}`;
};

